"""Minimal broker plugin interface for market research; order methods prohibited."""
from typing import Protocol,Any

class ResearchBroker(Protocol):
    name:str
    def configured(self)->bool:...
    def instruments(self)->list[dict[str,Any]]:...
    def history(self,item:dict,now=None,minutes:int=5,lookback_days:int=6,oi:bool=False):...
    def daily(self,item:dict,now=None,days:int=450,oi:bool=False):...
    def option_chain(self,item:dict,expiry:str)->dict:...
    def expiry_list(self,item:dict)->list[str]:...
